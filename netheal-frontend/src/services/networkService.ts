/**
 * Apply the current failure set and compute routes + metrics.
 * Currently a client-side BFS demonstration (baseline = fewest hops).
 * TODO(FastAPI): replace with POST /api/network/failures (NetworkX computes routes server-side).
 *   This function will become async; NetworkContext is the only caller to update.
 */
export function simulateNetwork(
  topology: Topology,
  failures: FailureState,
  source: string,
  destination: string,
): SimulationSnapshot {
  const route = findBaselineRoute(topology, failures, source, destination);
  const initialRoute = findBaselineRoute(topology, NO_FAILURES, source, destination);

  let alternatives = findAlternativeRoutes(topology, failures, source, destination, MAX_ALTERNATIVES);
  if (route && !alternatives.some((a) => routeKey(a) === routeKey(route))) {
    alternatives = [route, ...alternatives.slice(0, MAX_ALTERNATIVES - 1)];
  }

  const status: RouteStatus = !route
    ? 'unreachable'
    : initialRoute && routeKey(initialRoute) === routeKey(route)
      ? 'optimal'
      : 'rerouted';

  return { route, alternatives, status, counts: computeHealthCounts(topology, failures) };
}

